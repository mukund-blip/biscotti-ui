// Generates apps/web/src/catalog/index.ts from the catalog entries that exist.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const dir = join(import.meta.dirname, "../apps/web/src/catalog");
const files = readdirSync(dir).filter((f) => f.endsWith(".tsx")).map((f) => f.replace(/\.tsx$/, "")).sort();
const ident = (s) => "e_" + s.replace(/-/g, "_");
const src = `// AUTO-GENERATED by scripts/gen-catalog.mjs — do not edit.
import type { CatalogEntry, Group } from "./types";
${files.map((f) => `import { entry as ${ident(f)} } from "./${f}";`).join("\n")}

export const catalog: CatalogEntry[] = [${files.map(ident).join(", ")}].sort((a, b) => a.number.localeCompare(b.number));
export const groups: Group[] = ["Tactile controls", "Commands & composition", "Agent interactions", "Information & editing"];
export const bySlug = (slug: string) => catalog.find((e) => e.slug === slug);
`;
writeFileSync(join(dir, "index.ts"), src);
console.log(`catalog: ${files.length} entries`);
